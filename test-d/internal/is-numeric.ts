import {expectTypeOf} from 'nz';
import type {IsNumeric} from '../../source/internal/index.d.ts';

expectTypeOf<IsNumeric<''>>().toBe<false>();
expectTypeOf<IsNumeric<'0'>>().toBe<true>();
expectTypeOf<IsNumeric<'1'>>().toBe<true>();
expectTypeOf<IsNumeric<'-1'>>().toBe<true>();
expectTypeOf<IsNumeric<'123'>>().toBe<true>();
expectTypeOf<IsNumeric<'1e2'>>().toBe<true>();
expectTypeOf<IsNumeric<'1.23'>>().toBe<true>();
expectTypeOf<IsNumeric<'123.456'>>().toBe<true>();
expectTypeOf<IsNumeric<'1.23e4'>>().toBe<true>();
expectTypeOf<IsNumeric<'1.23e-4'>>().toBe<true>();
expectTypeOf<IsNumeric<' '>>().toBe<false>();
expectTypeOf<IsNumeric<'\n'>>().toBe<false>();
expectTypeOf<IsNumeric<'\u{9}'>>().toBe<false>();
expectTypeOf<IsNumeric<' 1.2'>>().toBe<false>();
expectTypeOf<IsNumeric<'1 2'>>().toBe<false>();
expectTypeOf<IsNumeric<'1_200'>>().toBe<false>();
expectTypeOf<IsNumeric<' 1 '>>().toBe<false>();
